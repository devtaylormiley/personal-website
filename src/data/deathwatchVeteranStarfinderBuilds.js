export function getFeatsForVeteranUpToLevel(veteranId, level) {
  const build = VETERAN_STARFINDER_BUILDS[veteranId]
  if (!build?.feats?.length) return []
  const clampedLevel = Math.min(20, Math.max(1, Number(level) || 1))
  return build.feats
    .filter((feat) => feat.level <= clampedLevel)
    .sort((a, b) => a.level - b.level || a.name.localeCompare(b.name))
}
